//! The start-up screen's logo from assets/hookshot.png: a C header with its
//! pixels as straight RGBA bytes. Ported from nx2/logo_rgba.py.

use std::fs;
use std::path::Path;

use serde_json::{Value, json};

/// Decode an 8-bit, non-interlaced RGBA or RGB PNG into RGBA bytes.
pub fn decode(path: &Path) -> Result<(u32, u32, Vec<u8>), String> {
    let file = fs::File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut decoder = png::Decoder::new(file);
    decoder.set_transformations(png::Transformations::IDENTITY);
    let mut reader = decoder
        .read_info()
        .map_err(|e| format!("{}: {e}", path.display()))?;
    let info = reader.info();
    if info.bit_depth != png::BitDepth::Eight || info.interlaced {
        return Err("only 8-bit RGB/RGBA, not interlaced".into());
    }
    let colour = info.color_type;
    let width = info.width;
    let height = info.height;
    let mut buffer = vec![0u8; reader.output_buffer_size()];
    let frame = reader
        .next_frame(&mut buffer)
        .map_err(|e| format!("{}: {e}", path.display()))?;
    let bytes = &buffer[..frame.buffer_size()];
    let pixels = match colour {
        png::ColorType::Rgba => bytes.to_vec(),
        png::ColorType::Rgb => bytes
            .chunks_exact(3)
            .flat_map(|px| [px[0], px[1], px[2], 0xff])
            .collect(),
        _ => return Err("only 8-bit RGB/RGBA, not interlaced".into()),
    };
    Ok((width, height, pixels))
}

pub fn header(png: &Path) -> Result<String, String> {
    if !png.is_file() {
        return Ok(
            "// generated by nx2/logo_rgba.py: no assets/hookshot.png\n#pragma once\n".into(),
        );
    }
    let (width, height, pixels) = decode(png)?;
    let mut lines = vec![
        "// generated by nx2/logo_rgba.py from assets/hookshot.png: do not edit".to_owned(),
        "#pragma once".to_owned(),
        "#define HOOKSHOT_LOGO 1".to_owned(),
        format!("static const unsigned hookshot_logo_w = {width}, hookshot_logo_h = {height};"),
        format!(
            "static const unsigned char hookshot_logo_rgba[{}] = {{",
            pixels.len()
        ),
    ];
    for chunk in pixels.chunks(32) {
        lines.push(format!(
            "{},",
            chunk
                .iter()
                .map(|byte| byte.to_string())
                .collect::<Vec<_>>()
                .join(",")
        ));
    }
    lines.push("};".to_owned());
    Ok(lines.join("\n") + "\n")
}

pub fn write(out: &Path, png: &Path) -> Result<String, String> {
    let text = header(png)?;
    let same = fs::read_to_string(out)
        .map(|old| old == text)
        .unwrap_or(false);
    if !same {
        if let Some(parent) = out.parent() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        fs::write(out, &text).map_err(|e| format!("{}: {e}", out.display()))?;
    }
    Ok(text)
}

pub fn write_json(out: &str, png: Option<&str>) -> Result<Value, String> {
    let root = crate::kit::root();
    let png = png
        .filter(|path| !path.is_empty())
        .map(Path::new)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| root.join("assets/hookshot.png"));
    let text = write(Path::new(out), &png)?;
    Ok(json!({"out": out, "bytes": text.len(), "found": png.is_file()}))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_the_checked_in_logo() {
        let png = crate::kit::root().join("assets/hookshot.png");
        if !png.is_file() {
            return;
        }
        let out = std::env::temp_dir().join(format!("hookshot-rust-logo-{}.h", std::process::id()));
        let _ = fs::remove_file(&out);
        let text = write(&out, &png).unwrap();
        assert!(text.contains("#define HOOKSHOT_LOGO 1"));
        assert!(text.contains("hookshot_logo_rgba["));
        assert!(text.lines().count() > 10);
        let _ = fs::remove_file(out);
    }
}
